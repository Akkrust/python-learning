# База данных пользователей.
# Ключ — логин, значение — пароль.
users = {
    "rustam": "pass123",
    "admin": "root55",
    "guest": "12345"
}

# Запрашиваем логин у пользователя.
login = input("Введите логин: ")

# Проверяем, существует ли введённый логин в словаре.
if login not in users:
    print("Пользователь не найден!")

    # Спрашиваем, хочет ли пользователь зарегистрироваться.
    register = input("Хотите зарегистрироваться? ").lower()

    # Если пользователь согласился, создаём новый аккаунт.
    if register == "да":

        # Запрашиваем пароль для нового аккаунта.
        new_password = input("Введите пароль: ")

        # Добавляем нового пользователя в словарь.
        # login становится новым ключом,
        # new_password становится его значением.
        users[login] = new_password

        print(
            "Регистрация прошла успешно. "
            "Добро пожаловать в ваше ТГ-хранилище!"
        )

    # Если пользователь отказался от регистрации.
    else:
        print("Доступ запрещён.")

else:
    # Если логин существует, запрашиваем пароль.
    password = input("Введите пароль: ")

    # Сравниваем введённый пароль с паролем,
    # который хранится в словаре для этого логина.
    if password != users[login]:
        print(
            "Неверный пароль, пожалуйста, "
            "убедитесь, что ввели пароль правильно."
        )

    # Если пароли совпали, предоставляем доступ.
    else:
        print(
            "Доступ разрешён! "
            "Добро пожаловать в ваше ТГ-хранилище!"
        )