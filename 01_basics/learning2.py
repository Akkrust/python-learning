# Начальное количество золота у игрока
gold = 500

# Цикл работает до тех пор, пока на балансе есть хоть какое-то золото
while gold > 0:

    # Сразу отнимаем 50 золота за одну попытку поиска базы
    gold = gold - 50
    print("Ищу противника в облаках... Потрачено 50 золота. Осталось:", gold)

    # Запрашиваем у пользователя решение.
    # Метод .lower() превращает любой ввод (ДА, Да, дА) в маленькие буквы "да"
    if input("Найдена база! Нападаем? (да/нет): ").lower() == "да":
        print("В бой! Бот завершает поиск.")
        break  # Полностью останавливаем цикл while и выходим из программы

    # Если после текущего поиска золота осталось меньше 50, то на следующий круг его точно не хватит
    elif gold < 50:
        print("Ресурсы кончились, поиск невозможен!")
        break  # Останавливаем цикл, так как продолжать поиск без денег нельзя

    # Если пользователь ответил "нет" и золота еще достаточно (>= 50), продолжаем поиск
    else:
        continue  # Принудительно отправляем цикл на следующий круг
