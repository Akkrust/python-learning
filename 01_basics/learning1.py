# Выводим приветственное сообщение в консоль
print("Добро пожаловать в симулятор фрилансера!")

# Запрашиваем у пользователя количество часов.
# input() принимает текст, а int() сразу превращает его в целое число.
hours = int(input("Сколько часов сегодня ты готов уделить кодингу? "))

# Продвинутый вложенный тернарный оператор (условия в одну строку).
# Логика проверяется последовательно слева направо в одну переменную 'result':
result = (
    "Этого мало, так ты джуниором не станешь! Иди учить Python!" if hours < 2
    else "Хороший темп! Ты отлично поработал сегодня и написал крутого бота!" if hours <= 5
    else "Ого, да ты маньяк кодинга! Ты написал целый бэкенд для сайта, но иди поспи, а то выгоришь!"
)

# Выводим на экран именно ту фразу, которая записалась в переменную 'result'
print(result)
