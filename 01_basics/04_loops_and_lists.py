# === ШАГ 1: Создаем пустой список для заказов ===
orders = []

# === ШАГ 2: Собираем заказы через цикл while ===
while True:
    user_input = input("Введите название заказа (или 'стоп' для завершения): ")

    # Метод .lower() превращает любой ввод ("СТОП", "Стоп") в "стоп"
    if user_input.lower() == "стоп":
        print("Сбор заказов завершен!\n")
        break  # Команда break полностью останавливает цикл while

    # Если пользователь ввел не "стоп", добавляем заказ в список
    orders.append(user_input)

# === ШАГ 3: Выводим общее количество заказов ===
# Функция len() считает, сколько элементов лежит в списке orders
print(f"У тебя в очереди заказов: {len(orders)}")
print("-" * 30)  # Просто красивая линия-разделитель

# === ШАГ 4: Обработка заказов через цикл for ===
total_hours = 0  # Сюда мы будем суммировать все заработанные деньги

for order in orders:
    # Цикл берет по ОДНОМУ заказу из списка и записывает его в переменную order
    # Используем f-строку, чтобы подставить имя заказа прямо в вопрос input
    price = int(input(f"Сколько стоит '{order}'? "))

    # Плюсуем цену текущего заказа к общей сумме заработка
    total_hours += price

    # Печатаем отчет по текущему заказу
    print(f"Выполняется заказ: {order}, оплата: {price}$\n")

# === ШАГ 5: Финальный анализ и тернарный оператор ===
print(f"Итого заработано: {total_hours}$")

# Тернарный оператор — это компактное ветвление в одну строку
# Синтаксис: [Результат_ЕСЛИ_ИСТИНА] if [Условие] else [Результат_ЕСЛИ_ЛОЖЬ]
# Но так как у нас 3 условия, мы вложили одно в другое:
status_message = (
    "Нужно поднажать, этого мало даже на кофе!" if total_hours < 100
    else "Отличный темп, ты на верном пути к Junior!" if total_hours <= 300
    else "Да ты маньяк фриланса! Иди поспи, а то выгоришь!"
)

# Печатаем финальный вердикт
print(status_message)
